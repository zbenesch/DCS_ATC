updated = []
skipped = []

for airfield, crps in crp_data.items():
    fname = file_map.get(airfield)
    fpath = os.path.join(airfield_dir, fname)
    if not os.path.exists(fpath):
        skipped.append(f"{airfield} (missing: {fpath})")
        continue

    with open(fpath, "r", encoding="utf-8") as f:
        content = f.read()

    new_crps = make_crps_block(airfield, crps)
    new_content = re.sub(r"    crps\s*=\s*\{.*?\},", new_crps, content, flags=re.DOTALL)

    if new_content == content:
        skipped.append(f"{airfield} (no crps block or unchanged)")
        continue

    with open(fpath, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)
    updated.append(airfield)

print("Updated:", updated)
print("Skipped:", skipped)
