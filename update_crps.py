def make_crps_block(airfield, crps):
    lines = ["    crps = {"]
    for seq, x, y, radius in crps:
        name = f"{airfield} CRP{seq}"
        lines.append(f"        {{ name=\"{name}\", seq={seq}, x={x},  y={y},  radius={radius} }},")
    lines.append("    },")
    return "\n".join(lines)

