function ATC.getRunway(abName)
    local rdata = (ATC.runways and next(ATC.runways) ~= nil) and ATC.runways or _runwaySnapshot
    if not rdata or not abName then
        ATC.debugLog(string.format("getRunway: abName=nil or rdata=nil (abName=%s)", tostring(abName)))
        return nil
    end
    -- Hits are not logged: this is called several times a second per aircraft and
    -- accounted for a third of the entire log file. Only the interesting
    -- outcomes are recorded, and only when they change.
    local exact = rdata[abName]
    if exact then return exact end

    local norm = normalizeAirbaseName(abName)
    if not norm then return nil end

    local aliasKey = _AIRBASE_ALIASES[norm]
    if aliasKey and rdata[aliasKey] then
        ATC.logChange("rwyalias|" .. abName, string.format(
            "RWY   '%s' resolved via alias -> '%s'", tostring(abName), aliasKey))
        return rdata[aliasKey]
    end

    for key, value in pairs(rdata) do
        if normalizeAirbaseName(key) == norm then
            ATC.logChange("rwynorm|" .. abName, string.format(
                "RWY   '%s' resolved by normalised name -> '%s'", tostring(abName), key))
            return value
        end
    end

    ATC.logChange("rwymiss|" .. tostring(abName), string.format(
        "RWY   NO CONFIG for '%s' (norm='%s') -- no ATC at this field",
        tostring(abName), tostring(norm)))
    return nil
end
function ATC.distVec3(a, b)
    if not a or not b or type(a.x) ~= "number" or type(b.x) ~= "number"
       or type(a.y) ~= "number" or type(b.y) ~= "number"
       or type(a.z) ~= "number" or type(b.z) ~= "number" then
        return math.huge
    end
    local dx = a.x - b.x
    local dy = a.y - b.y
    local dz = a.z - b.z
    return math.sqrt(dx*dx + dy*dy + dz*dz)
end
function ATC.distVec3H(a, b)
    if not a or not b or type(a.x) ~= "number" or type(b.x) ~= "number"
       or type(a.z) ~= "number" or type(b.z) ~= "number" then
        return math.huge
    end
    local dx = a.x - b.x
    local dz = a.z - b.z
    return math.sqrt(dx*dx + dz*dz)
end
-- Ground taxi routing --------------------------------------------------------
-- Point-in-polygon (ray casting). DCS coords: pos.x=northing, pos.z=easting.
-- verts: array of {x=northing, y=easting} (zone config format).
local function _pointInPoly(pos, verts)
    local px, py = pos.x, pos.z
    local n = #verts
    local inside = false
    local j = n
    for i = 1, n do
        local xi, yi = verts[i].x, verts[i].y
        local xj, yj = verts[j].x, verts[j].y
        if ((yi > py) ~= (yj > py)) and
           (px < (xj - xi) * (py - yi) / (yj - yi) + xi) then
            inside = not inside
        end
        j = i
    end
    return inside
end

-- Returns the zone key (e.g. "taxi_a1", "holdshort_33") the unit is in,
-- or nil if none. Checks all keys in rwy config that have a verts sub-table
-- or are a flat array of {x,y} vertices.
function ATC.findGroundZone(unitPos, rwy)
    if not unitPos or not rwy then return nil end
    for key, zone in pairs(rwy) do
        if type(zone) == "table" then
            local verts
            if zone.verts and type(zone.verts) == "table" then
                verts = zone.verts
            elseif zone[1] and type(zone[1]) == "table" and zone[1].x then
                verts = zone
            end
            if verts and #verts >= 3 and _pointInPoly(unitPos, verts) then
                return key
            end
        end
    end
    return nil
end

-- BFS shortest path from fromZone to toZone through the adjacency graph.
-- graph: { [zoneKey] = { neighbor1, neighbor2, ... } }
-- Returns list of zone keys including start and end, or nil if unreachable.
function ATC.planTaxiRoute(fromZone, toZone, graph)
    if not fromZone or not toZone or not graph then return nil end
    if fromZone == toZone then return { fromZone } end
    if not graph[fromZone] then return nil end
    local visited = { [fromZone] = true }
    local queue = { { fromZone } }
    while #queue > 0 do
        local path = table.remove(queue, 1)
        local current = path[#path]
        for _, neighbor in ipairs(graph[current] or {}) do
            if not visited[neighbor] then
                local newPath = {}
                for _, v in ipairs(path) do newPath[#newPath+1] = v end
                newPath[#newPath+1] = neighbor
                if neighbor == toZone then return newPath end
                visited[neighbor] = true
                queue[#queue+1] = newPath
            end
        end
    end
    return nil
end

-- Converts a zone path into an ordered list of taxiway letter labels,
-- collapsing consecutive segments of the same letter into one.
-- zoneLabel: { [zoneKey] = "alpha" | "whiskey" | ... }
-- Returns e.g. {"alpha","whiskey"} — only zones with a label entry.
function ATC.taxiRouteLabels(path, zoneLabel)
    if not path or not zoneLabel then return {} end
    local labels = {}
    local last = nil
    for _, zone in ipairs(path) do
        local lbl = zoneLabel[zone]
        if lbl and lbl ~= last then
            labels[#labels+1] = lbl
            last = lbl
        end
    end
    return labels
end
