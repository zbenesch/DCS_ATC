--- Returns the closest unoccupied parking spot to a unit, or nil.
--- Spot table has: Term_Index (number), vTerminalPos (Vec3), TO_AC (bool).
function ATC.getClosestParking(unit, ab)
    if not unit or not ab then return nil end
    local ok, spots = pcall(function() return ab:getParking() end)
    if not ok or not spots then return nil end
    local uPos = unit:getPoint()
    local best, bestDist = nil, math.huge
    for _, spot in ipairs(spots) do
        if not spot.TO_AC then
            local sPos = spot.vTerminalPos
            if sPos then
                local d = ATC.distVec3H(uPos, sPos)
                if d < bestDist then
                    bestDist = d
                    best = spot
                end
            end
        end
    end
    return best
end

