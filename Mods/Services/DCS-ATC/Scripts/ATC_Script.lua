        end
    end
    if env and env.info then
        env.info("DCS-ATC " .. line)
    end
end
local _phraseSeqId = 0
local _missingVoiceClipLogged = {}
local function getPhraseAudioPath(voice, token)
    -- Always use .miz internal path for radioTransmission
    return string.format("AUDIO/atc/%s/%s.ogg", voice, token)
end

function ATC.getControllerRadio(abName, controller)
    local rwy     = ATC.runways and ATC.runways[abName]
    local freqs   = rwy and rwy.frequencies
    local ctrlKey = (controller or "Approach"):lower()
    local freqRec = freqs and freqs[ctrlKey]
    local fallback = freqs and freqs.approach
    local radio   = freqRec or fallback or {}
    local freqHz  = radio.hz or 251000000
    local modulation = radio.modulation
    if modulation == nil then
        modulation = ATC.config.radioModulation or 0
    end
    local power = radio.power or ATC.config.radioTxPower or 1000
    return freqHz, modulation, power
end

function ATC.scheduleTokens(groupId, abPos, freqHz, tokens, voice, startT, modulation, power)
    _phraseSeqId = _phraseSeqId + 1
    local seqId = _phraseSeqId
    ATC.voiceDebug(groupId, string.format(
        "TX seq=%d voice=%s tokens=%d", seqId, tostring(voice), #tokens))
    local t = startT
    local phraseDur = ATC._phraseDur or {}
    for i, token in ipairs(tokens) do
        local clipKey = voice .. "/" .. token
        local dur = phraseDur[clipKey] or 0.45  -- fallback duration for tokens without measured duration
        if not phraseDur[clipKey] then
            if not _missingVoiceClipLogged[clipKey] then
                _missingVoiceClipLogged[clipKey] = true
                ATC.log("WARN  VOICE missing dur: " .. tostring(clipKey))
            end
        end
        local name = string.format("ATC_%d_%d", seqId, i)
        local path = getPhraseAudioPath(voice, token)
        ATC.voiceDebug(groupId, string.format("TX %s %.2f", token, t))
        local _pos, _f, _n, _p, _m, _w = abPos, freqHz, name, path, modulation, power
        timer.scheduleFunction(function()
            trigger.action.radioTransmission(_p, _pos, _m, false, _f, _w, _n)
            return nil
        end, nil, t)
        t = t + dur  -- no gap; clips are silence-trimmed at both ends
    end
end

-- Convert an altitude number to spoken word form: 4500 -> "four thousand five hundred"
local function altToWords(n)
    local dw = ATC._DWORDS or {}
    n = math.floor(tonumber(n) or 0)
    local th = math.floor(n / 1000)
    local hd = math.floor((n % 1000) / 100)
    if th > 0 and th <= 9 then
        local parts = { dw[th] or tostring(th), "thousand" }
        if hd > 0 then
            table.insert(parts, dw[hd] or tostring(hd))
            table.insert(parts, "hundred")
        end
        return table.concat(parts, " ")
    end
    -- fallback: digit by digit
    local parts = {}
    for d in tostring(n):gmatch(".") do
        table.insert(parts, dw[tonumber(d)] or d)
    end
    return table.concat(parts, " ")
end

-- Spoken number words for distances and QFE (not ICAO digit pronunciation)
local _WORD_NUMS = {
    [0]="zero",[1]="one",[2]="two",[3]="three",[4]="four",[5]="five",
    [6]="six",[7]="seven",[8]="eight",[9]="nine",[10]="ten",
    [11]="eleven",[12]="twelve",[13]="thirteen",[14]="fourteen",
    [15]="fifteen",[16]="sixteen",[17]="seventeen",[18]="eighteen",
    [19]="nineteen",[20]="twenty",[30]="thirty",[40]="forty",[50]="fifty",
    [60]="sixty",[70]="seventy",[80]="eighty",[90]="ninety",
}
-- Convert integer 0-99 to spoken word(s); nil-safe
local function numToWordStr(n)
    n = math.floor(n or 0)
    if n < 0 then n = 0 end
    if _WORD_NUMS[n] then return _WORD_NUMS[n] end
    local tens  = math.floor(n / 10) * 10
    local units = n % 10
    return (_WORD_NUMS[tens] or tostring(tens)) .. " " .. (_WORD_NUMS[units] or tostring(units))
end
-- Convert NM distance to spoken words (1-50); >50 → outside-airspace token
-- Rounding: .5 rounds DOWN, .6 rounds UP  (math.floor(x + 0.4))
local function nmToWordStr(x)
    local n = math.floor(x + 0.4)
    if n < 1 then n = 1 end
    if n > 50 then return "__outside_my_airspace__" end
    return numToWordStr(n)
end

function ATC.textToTokens(text)
    if ATC and ATC.config and ATC.config.disableVoice then return {} end
    if not text or text == "" then return {} end
    text = text:lower()
    text = text:gsub("[\n\r]", " ")
    text = text:gsub("%-", " ")
    for _, sub in ipairs(ATC._PSUBS or {}) do
        text = text:gsub(sub[1], sub[2])
    end
    -- Altitude: "4500 ft" -> "four thousand five hundred ft" (before ft->feet)
    text = text:gsub("(%d+) ft", function(n) return altToWords(n) .. " ft" end)
    -- NM distances: round to integer, expand to spoken word(s) + nautical-miles
    -- Handles "15.3 nm", "15 nm"; replaces decimal form too (no "point" in output)
    text = text:gsub("(%d+%.%d+) nm", function(s)
        return nmToWordStr(tonumber(s) or 1) .. " nautical-miles"
    end)
    text = text:gsub("(%d+) nm", function(s)
        return nmToWordStr(tonumber(s) or 1) .. " nautical-miles"
    end)
    -- Short-distance "miles" (used in vector instructions): same rounding, no outside-airspace cap
    text = text:gsub("(%d+%.%d+) miles", function(s)
        local n = math.floor((tonumber(s) or 1) + 0.4)
        if n < 1 then n = 1 end
        return numToWordStr(math.min(n, 50)) .. " miles"
    end)
    text = text:gsub("(%d+) miles", function(s)
        local n = tonumber(s) or 1
        return numToWordStr(math.min(n, 50)) .. " miles"
    end)
    -- QFE inHg: "qfe 29.83" -> "qfe twenty nine decimal eighty three"
    text = text:gsub("qfe (%d+)%.(%d+)", function(intS, fracS)
        return "qfe " .. numToWordStr(tonumber(intS) or 0) ..
               " decimal " .. numToWordStr(tonumber(fracS) or 0)
    end)
    -- QFE hPa (integer, Russian): "qfe 970" -> "qfe nine seven zero" (digit split kept)
    text = text:gsub(" kt", " knots")
    text = text:gsub(" ft", " feet")
    -- General decimals (non-NM, non-QFE): "120.1" -> "120 point 1"
    text = text:gsub("(%d+)%.(%d+)", "%1 point %2")
    text = text:gsub("[%.,!%;:%?%(%)%[%]]", " ")
    text = text:gsub("%s+", " ")
    text = text:gsub("^%s+", ""):gsub("%s+$", "")
    local tokens = {}
    -- Special handling for callsign + number at start
    local callsign, num, rest = text:match("^(%w+)%s+(%d%d)%s*(.*)$")
    if callsign and ATC._CALLSIGNS[callsign] then
        table.insert(tokens, callsign)
        for d in num:gmatch(".") do
            local dw = (ATC._DWORDS or {})[tonumber(d)]
            if dw then table.insert(tokens, dw) end
        end
        text = rest or ""
    end
    local wset = ATC._WSET or {}
    local csigns = ATC._CALLSIGNS or {}
    local dwords = ATC._DWORDS or {}
    for word in text:gmatch("[%w_%-]+") do
        if word:match("^__(.-)__$") then
            local chunk = word:match("^__(.-)__$"):gsub("_", "-")
            chunk = chunk:gsub("[^%w%-]", ""):gsub("%-+", "-"):gsub("^%-+", ""):gsub("%-+$", "")
            if chunk ~= "" then
                table.insert(tokens, chunk)
            end
        elseif word:match("^%d+$") then
            -- Split into individual digit tokens (ICAO: "one two zero")
            for d in word:gmatch(".") do
                local dw = dwords[tonumber(d)]
                if dw then table.insert(tokens, dw) end
            end
        elseif wset[word] then
            table.insert(tokens, word)
        elseif csigns[word] then
            table.insert(tokens, word)
        else
            -- Try to split mid-text callsign+number: "colt11" -> "colt","one","one"
            local alpha, digits = word:match("^(%a+)(%d+)$")
            if alpha and (csigns[alpha] or wset[alpha]) then
                if wset[alpha] or csigns[alpha] then
                    table.insert(tokens, alpha)
                end
                for d in digits:gmatch(".") do
                    local dw = dwords[tonumber(d)]
                    if dw then table.insert(tokens, dw) end
                end
            end
            -- else: unknown word, skip
        end
    end
    return tokens
end
local _PHRASE_VOICES = { "adam", "alice", "daniel", "gary", "david", "diane", "olivia", "brad" }

-- Randomly assign a unique voice to each controller role on mission load.
-- Fisher-Yates shuffle over the pool; first N entries go to the roles.
local function _buildRoleVoices()
    local roles = { "approach", "tower", "ground", "departure" }
    local pool  = {}
    for _, v in ipairs(_PHRASE_VOICES) do pool[#pool + 1] = v end
    for i = #pool, 2, -1 do
        local j = math.random(1, i)
        pool[i], pool[j] = pool[j], pool[i]
    end
    local t = {}
    for i, r in ipairs(roles) do t[r] = pool[i] end
    return t
end
local _ROLE_VOICE = _buildRoleVoices()

function ATC.getStationVoice(abName, role)
    local r = role and role:lower()
    if _ROLE_VOICE[r] then return _ROLE_VOICE[r] end
    -- Fallback for any unlisted controller type: hash to a voice.
    local s = (abName or "") .. (role or "")
    local h = 0
    for i = 1, #s do h = h + string.byte(s, i) end
    return _PHRASE_VOICES[(h % #_PHRASE_VOICES) + 1]
end
