airfield_dir = "k:/DCS_ATC/Mods/Services/DCS-ATC/Scripts/airfields/Caucasus"

updated = []
skipped = []

for airfield, crps in crp_data.items():
    fname = file_map.get(airfield)
    fpath = os.path.join(airfield_dir, fname)
    if not os.path.exists(fpath):
        skipped.append(f"{airfield} (file not found)")
        continue

    with open(fpath, "r", encoding="utf-8") as f:
        content = f.read()

    crps_match = re.search(r'\n[ \t]*crps\s*=', content)
    if not crps_match:
        skipped.append(f"{airfield} (no crps field)")
        continue

    prefix = content[:crps_match.start()]

    # Build crps block
    crp_lines = ["    crps = {"]
    for seq, x, y, radius in crps:
        crp_lines.append(f'        {{ name="{airfield} CRP{seq}", seq={seq}, x={x}, y={y}, radius={radius} }},')
    crp_lines.append("    },")
    crps_block = "\n".join(crp_lines)

    # Build rwy block
    verts = rwy_data.get(airfield)
    if verts:
        rwy_lines = ["    rwy = {"]
        for x, y in verts:
            rwy_lines.append(f"        {{ x={x}, y={y} }},")
        rwy_lines.append("    },")
        rwy_block = "\n" + "\n".join(rwy_lines)
    else:
        rwy_block = ""

    new_content = prefix + "\n" + crps_block + rwy_block + "\n}\n"

    with open(fpath, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)
    updated.append(airfield)

print("Updated:", updated)
print("Skipped:", skipped)
